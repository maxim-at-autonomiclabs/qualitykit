#!/usr/bin/env node
/**
 * Workers Builds monorepo helper.
 *
 * postinstall (when WORKERS_CI=1): install a wrangler shim in node_modules/.bin
 * so bare `npx wrangler deploy` can see WRANGLER_CI_OVERRIDE_NAME (set at deploy
 * time) and select the right Worker.
 *
 * When invoked with WRANGLER_CI_OVERRIDE_NAME already set: build that package and
 * write a root wrangler.toml with repo-root-relative paths.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const worker = process.env.WRANGLER_CI_OVERRIDE_NAME;
const inWorkersCi = process.env.WORKERS_CI === "1" || process.env.WORKERS_CI === "true";

function run(command, args) {
  console.log(`[cf-prepare] > ${command} ${args.join(" ")}`);
  const result = spawnSync(command, args, {
    cwd: root,
    stdio: "inherit",
    shell: process.platform === "win32",
    env: process.env,
  });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

function installWranglerShim() {
  const shimSrc = path.join(root, "scripts", "wrangler-ci-shim.mjs");
  // npx resolves the package bin (node_modules/wrangler/bin/wrangler.js), not
  // always .bin — patch the package entry and keep a copy of the real CLI.
  const pkgBins = [
    path.join(root, "node_modules", "wrangler", "bin", "wrangler.js"),
    path.join(root, "cloud", "node_modules", "wrangler", "bin", "wrangler.js"),
  ];

  for (const pkgBin of pkgBins) {
    if (!fs.existsSync(pkgBin)) continue;
    const realCopy = path.join(path.dirname(pkgBin), "wrangler.real.js");
    try {
      if (!fs.existsSync(realCopy)) {
        fs.copyFileSync(pkgBin, realCopy);
      }
      fs.writeFileSync(
        pkgBin,
        `#!/usr/bin/env node
import { pathToFileURL } from "node:url";
await import(pathToFileURL(${JSON.stringify(shimSrc)}).href);
`,
        { mode: 0o755 },
      );
      console.log(`[cf-prepare] patched ${pkgBin}`);
    } catch (err) {
      console.warn(`[cf-prepare] could not patch ${pkgBin}:`, err.message);
    }
  }
}

function writeConfig(name, body) {
  const out = path.join(root, "wrangler.toml");
  fs.writeFileSync(out, `# Generated by scripts/cf-prepare.mjs for ${name}\n${body}`);
  console.log(`[cf-prepare] wrote ${out}`);
}

function prepareWorker(name) {
  if (name === "qualitykit-web") {
    run("npm", ["run", "build", "--prefix", "website"]);
    writeConfig(
      name,
      `name = "qualitykit-web"
main = "website/src/worker.js"
compatibility_date = "2025-11-15"
workers_dev = true

routes = [
  { pattern = "qualitykit.dev", custom_domain = true },
  { pattern = "www.qualitykit.dev", custom_domain = true }
]

[assets]
directory = "./website/dist"
binding = "ASSETS"
html_handling = "auto-trailing-slash"
not_found_handling = "404-page"
`,
    );
    return;
  }

  if (name === "qualitykit-cloud") {
    run("npm", ["run", "build:engine"]);
    writeConfig(
      name,
      `name = "qualitykit-cloud"
main = "cloud/src/index.ts"
compatibility_date = "2025-11-15"
workers_dev = true

routes = [
  { pattern = "app.qualitykit.dev", custom_domain = true }
]

[[d1_databases]]
binding = "DB"
database_name = "qualitykit"
database_id = "fd391b59-d80e-42cb-977a-d72eebaf33ed"
migrations_dir = "cloud/migrations"

[[queues.producers]]
binding = "CRAWL_QUEUE"
queue = "qualitykit-crawl"

[[queues.consumers]]
queue = "qualitykit-crawl"
max_batch_size = 5
max_retries = 3

[triggers]
crons = ["0 6 * * *"]

[assets]
directory = "./cloud/public"
binding = "ASSETS"
html_handling = "none"
not_found_handling = "404-page"

[vars]
APP_URL = "https://app.qualitykit.dev"
STRIPE_PRICE_ID = "price_REPLACE_ME"
CLERK_PUBLISHABLE_KEY = "pk_live_Y2xlcmsucXVhbGl0eWtpdC5kZXYk"
`,
    );
    return;
  }

  console.error(`[cf-prepare] unknown worker "${name}"`);
  process.exit(1);
}

// --- entry ---
if (worker) {
  prepareWorker(worker);
  process.exit(0);
}

if (inWorkersCi) {
  installWranglerShim();
  process.exit(0);
}

// Local npm install — no-op
process.exit(0);
